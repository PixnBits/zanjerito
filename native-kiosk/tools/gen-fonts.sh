#!/usr/bin/env bash
# Generate LVGL v9 C fonts from fonts/*.ttf into generated/.
# Uses lv_font_conv 1.5.3 (npx). Output is deterministic for a given tool version.
# Literata sources are static SemiBold instances (see fonts/README.md).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GEN="$ROOT/generated"
CONV_PKG="lv_font_conv@1.5.3"

if ! command -v npx >/dev/null 2>&1; then
  # shellcheck disable=SC1090
  source "${HOME}/.nvm/nvm.sh"
fi

mkdir -p "$GEN"
cd "$ROOT"

# Drop previous subsets so unused faces (Alfa, ExtraBold) cannot linger.
rm -f "$GEN"/zk_font_*.c

CONV=(npx --yes "$CONV_PKG")
CONV_VER="$("${CONV[@]}" -v 2>/dev/null | tail -n 1)"
CONV_VER="${CONV_VER:-1.5.3}"

# Printable ASCII, Latin-1 (U+00A0–U+00FF), en/em dash, quotes, bullet,
# ellipsis, single right angle quote.
# U+26A0 is not in these fonts; the kiosk draws the warning triangle.
# Display strings are folded in zk_text_display; the extra punctuation is
# here so a literal that still uses it does not draw a placeholder box.
GLYPHS="0x20-0x7E,0xA0-0xFF,0x2013,0x2014,0x2018,0x2019,0x201C,0x201D,0x2022,0x2026,0x203A"

gen_one() {
  local ttf="$1" name="$2" size="$3"
  local rel="generated/${name}.c"
  echo "font ${name} size=${size}"
  "${CONV[@]}" \
    --bpp 4 \
    --no-compress \
    --no-prefilter \
    --format lvgl \
    --lv-include lvgl.h \
    --lv-font-name "$name" \
    --font "$ttf" \
    --size "$size" \
    --range "$GLYPHS" \
    -o "$rel"
  local tmp
  tmp="$(mktemp)"
  {
    echo "/* Generated by lv_font_conv ${CONV_VER}; do not edit. */"
    cat "$rel"
  } >"$tmp"
  chmod 644 "$tmp"
  mv "$tmp" "$rel"
  # Accented Latin raises the converter's line box. The kiosk rows were drawn
  # against the previous metrics (Literata 32 is 35 px). Keep those numbers so
  # a ring or acute cannot restack every screen. The glyph is still present.
  pin_metrics "$name" "$rel"
}

# name, line_height, base_line — the values shipped before Latin-1 was added.
pin_metrics() {
  local name="$1" file="$2" lh bl
  case "$name" in
    zk_font_r_20) lh=20; bl=4 ;;
    zk_font_r_22) lh=22; bl=4 ;;
    zk_font_r_24) lh=24; bl=5 ;;
    zk_font_r_26) lh=26; bl=5 ;;
    zk_font_m_18) lh=17; bl=3 ;;
    zk_font_m_20) lh=19; bl=4 ;;
    zk_font_m_26) lh=27; bl=5 ;;
    zk_font_m_28) lh=29; bl=6 ;;
    zk_font_sb_18) lh=18; bl=3 ;;
    zk_font_sb_24) lh=26; bl=5 ;;
    zk_font_sb_26) lh=27; bl=5 ;;
    zk_font_sb_36) lh=36; bl=7 ;;
    zk_font_b_30) lh=31; bl=6 ;;
    zk_font_b_36) lh=38; bl=8 ;;
    zk_font_lit_18) lh=22; bl=5 ;;
    zk_font_lit_20) lh=23; bl=5 ;;
    zk_font_lit_26) lh=29; bl=6 ;;
    zk_font_lit_32) lh=35; bl=7 ;;
    zk_font_lit_40) lh=43; bl=10 ;;
    zk_font_lit_48) lh=52; bl=12 ;;
    *) return 0 ;;
  esac
  python3 - "$file" "$lh" "$bl" <<'PY'
import pathlib, re, sys
path, lh, bl = sys.argv[1:]
file = pathlib.Path(path)
text = file.read_text()
text2, n1 = re.subn(r"(\.line_height = )\d+", r"\g<1>" + lh, text, count=1)
text2, n2 = re.subn(r"(\.base_line = )\d+", r"\g<1>" + bl, text2, count=1)
if n1 != 1 or n2 != 1:
    raise SystemExit("pin_metrics: %s line_height=%d base_line=%d" % (path, n1, n2))
file.write_text(text2)
PY
}

# r: Barlow Semi Condensed Regular (400)
for s in 20 22 24 26; do
  gen_one "fonts/BarlowSemiCondensed-Regular.ttf" "zk_font_r_${s}" "$s"
done

# m: Medium (500)
for s in 18 20 26 28; do
  gen_one "fonts/BarlowSemiCondensed-Medium.ttf" "zk_font_m_${s}" "$s"
done

# sb: SemiBold (600)
for s in 18 24 26 36; do
  gen_one "fonts/BarlowSemiCondensed-SemiBold.ttf" "zk_font_sb_${s}" "$s"
done

# b: Bold (700)
for s in 30 36; do
  gen_one "fonts/BarlowSemiCondensed-Bold.ttf" "zk_font_b_${s}" "$s"
done

# lit: Literata SemiBold. Text optical size for small sizes, Display for large.
for s in 18 20 26 32; do
  gen_one "fonts/Literata-SemiBold-Text.ttf" "zk_font_lit_${s}" "$s"
done
for s in 40 48; do
  gen_one "fonts/Literata-SemiBold.ttf" "zk_font_lit_${s}" "$s"
done

HEADER="$GEN/zk_fonts.h"
{
  echo "/* Generated by tools/gen-fonts.sh using lv_font_conv ${CONV_VER}; do not edit. */"
  echo "#ifndef ZK_FONTS_H"
  echo "#define ZK_FONTS_H"
  echo
  echo "#ifdef __cplusplus"
  echo "extern \"C\" {"
  echo "#endif"
  echo
  echo "#ifdef LV_LVGL_H_INCLUDE_SIMPLE"
  echo "#include \"lvgl.h\""
  echo "#else"
  echo "#include \"lvgl.h\""
  echo "#endif"
  echo
  for name in \
    zk_font_r_20 zk_font_r_22 zk_font_r_24 zk_font_r_26 \
    zk_font_m_18 zk_font_m_20 zk_font_m_26 zk_font_m_28 \
    zk_font_sb_18 zk_font_sb_24 zk_font_sb_26 zk_font_sb_36 \
    zk_font_b_30 zk_font_b_36 \
    zk_font_lit_18 zk_font_lit_20 zk_font_lit_26 zk_font_lit_32 zk_font_lit_40 zk_font_lit_48
  do
    echo "LV_FONT_DECLARE(${name});"
  done
  echo
  echo "#ifdef __cplusplus"
  echo "}"
  echo "#endif"
  echo
  echo "#endif /* ZK_FONTS_H */"
} >"$HEADER"

echo "wrote ${HEADER}"
